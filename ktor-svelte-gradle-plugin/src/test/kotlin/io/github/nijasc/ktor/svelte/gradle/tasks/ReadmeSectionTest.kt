package io.github.nijasc.ktor.svelte.gradle.tasks

import org.junit.jupiter.api.io.TempDir
import java.io.File
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull

class ReadmeSectionTest {
    @TempDir
    lateinit var dir: File

    private val facts =
        ReadmeFacts(
            taskPrefix = "",
            tasks = setOf("svelteDevAll", "svelteGenerateTs", "run", "shadowJar"),
            appUrl = "http://localhost:8080",
            devPort = 5173,
            debugPort = 5005,
            httpsPort = null,
            variables = listOf(EnvironmentVariable("SESSION_KEY", "Signs the session.", required = true)),
            buildEnv = listOf("PUBLIC_SENTRY_DSN"),
        )

    @Test
    fun `the section lists the commands, addresses and environment variables`() {
        assertEquals(
            """
            ### Commands

            | Command | What it does |
            |---|---|
            | `./gradlew svelteDevAll` | Runs the app, Vite and the Kotlin compiler, and restarts the app when Kotlin changes |
            | `./gradlew build` | Builds the frontend and the app, and runs the tests |
            | `./gradlew shadowJar` | Packages the app with the frontend into one JAR |
            | `./gradlew run` | Starts the app |
            | `./gradlew check` | Runs the tests and the checks |
            | `./gradlew svelteSync svelteGenerateTs` | Writes the generated frontend files and the TypeScript client again |
            | `./gradlew svelteDoctor` | Checks the frontend setup and says what to fix |

            ### Addresses in development

            | What | Address |
            |---|---|
            | App | http://localhost:8080 |
            | Vite dev server | http://localhost:5173 |
            | Debugger of the app started by svelteDevAll | localhost:5005 |

            ### Environment variables

            | Variable | Read by | What it is |
            |---|---|---|
            | `SESSION_KEY` | app | Signs the session. Required. |
            | `PUBLIC_SENTRY_DSN` | frontend build | Declared in `svelte { buildEnv }` |

            """.trimIndent(),
            readmeSection(facts),
        )
    }

    @Test
    fun `a library project gets fewer commands, a subproject its path, and no variables means no table`() {
        val library = facts.copy(taskPrefix = ":web:", tasks = emptySet(), appUrl = null, debugPort = 0)
        val section = readmeSection(library.copy(variables = emptyList(), buildEnv = emptyList()))
        assertEquals(
            listOf("`./gradlew :web:build`", "`./gradlew :web:jar`", "`./gradlew :web:check`", "`./gradlew :web:svelteDoctor`"),
            Regex("`./gradlew [^`]+`").findAll(section).map { it.value }.toList(),
        )
        assertEquals(false, "Environment variables" in section)
        assertEquals(false, "Debugger" in section)
    }

    @Test
    fun `only the text between the markers is replaced, with the file's line endings`() {
        val readme = "# App\r\n\r\nIntro.\r\n$README_START\r\nold\r\n$README_END\r\nOutro.\r\n"
        assertEquals(
            "# App\r\n\r\nIntro.\r\n$README_START\r\n\r\n### New\r\n\r\nrow\r\n\r\n$README_END\r\nOutro.\r\n",
            replaceBetweenMarkers(readme, "### New\n\nrow\n"),
        )
        assertNull(replaceBetweenMarkers("# App\n", "x"))
        assertNull(replaceBetweenMarkers("$README_END\n$README_START\n", "x"))
    }

    @Test
    fun `variables come from the env example the app writes`() {
        val example = dir.resolve(".env.example")
        example.writeText(
            listOf(
                "# Generated by ktor-svelte from the environment variables the app declares. Do not edit.",
                "",
                "# Port the server listens on. A whole number. Default: 8080.",
                "# PORT=8080",
                "",
                "# Signs the session. Required. Secret.",
                "SESSION_KEY=",
            ).joinToString("\n"),
        )
        assertEquals(
            listOf(
                EnvironmentVariable("PORT", "Port the server listens on. A whole number. Default: 8080.", required = false),
                EnvironmentVariable("SESSION_KEY", "Signs the session. Required. Secret.", required = true),
            ),
            environmentVariables(example),
        )
        assertEquals(emptyList(), environmentVariables(dir.resolve("missing")))
    }
}
