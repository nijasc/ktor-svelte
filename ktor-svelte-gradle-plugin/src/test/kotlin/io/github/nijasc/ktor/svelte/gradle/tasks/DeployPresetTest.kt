package io.github.nijasc.ktor.svelte.gradle.tasks

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNull

class DeployPresetTest {
    @Test
    fun `the start command follows the way the project builds its jar`() {
        val fat = startPlan("shop", setOf("jar", "buildFatJar", "shadowJar"))
        assertEquals("./gradlew buildFatJar --no-daemon" to "java -jar build/libs/shop-all.jar", fat.build to fat.start)
        val shadow = startPlan("shop", setOf("jar", "shadowJar"))
        assertEquals("./gradlew shadowJar --no-daemon" to "java -jar build/libs/shop-all.jar", shadow.build to shadow.start)
        val plain = startPlan("shop", setOf("jar", "installDist"))
        assertEquals("./gradlew installDist --no-daemon" to "build/install/shop/bin/shop", plain.build to plain.start)
    }

    @Test
    fun `required variables are read from the example file, in its order`() {
        val example =
            listOf(
                "# Generated by ktor-svelte from the environment variables the app declares. Do not edit.",
                "",
                "# JDBC URL of the database. Required.",
                "DATABASE_URL=jdbc:postgresql://localhost/app",
                "",
                "# Port the server listens on. A whole number. Default: 8080.",
                "# PORT=8080",
                "",
                "# Signs the session cookie. Required. Secret.",
                "SESSION_SIGN_KEY=",
                "",
                "# Token of the mail service. Optional. Secret.",
                "# MAIL_TOKEN=",
                "",
            ).joinToString("\n")
        assertEquals(listOf("DATABASE_URL", "SESSION_SIGN_KEY"), requiredVariables(example))
        assertEquals(emptyList(), requiredVariables(""))
    }

    @Test
    fun `the repository comes from the origin remote when it is on GitHub`() {
        val https = "[core]\n\tbare = false\n[remote \"origin\"]\n\turl = https://github.com/acme/shop.git\n\tfetch = +refs/heads/*\n"
        assertEquals("acme/shop", githubRepository(https))
        assertEquals("acme/shop", githubRepository("[remote \"origin\"]\n\turl = git@github.com:acme/shop\n"))
        assertNull(githubRepository("[remote \"origin\"]\n\turl = https://gitlab.com/acme/shop.git\n"))
        assertNull(githubRepository("[remote \"upstream\"]\n\turl = https://github.com/other/shop.git\n"))
    }

    @Test
    fun `the Railway file has the service with its source, commands, health check and variables`() {
        val plan = StartPlan("./gradlew buildFatJar --no-daemon", "java -jar build/libs/shop-all.jar")
        assertEquals(
            listOf(
                "import { defineRailway, github, preserve, project, service } from \"railway/iac\";",
                "",
                "export default defineRailway(() => {",
                "    const app = service(\"shop\", {",
                "        source: github(\"acme/shop\"),",
                "        build: \"./gradlew buildFatJar --no-daemon\",",
                "        start: \"java -jar build/libs/shop-all.jar\",",
                "        healthcheck: \"/_ktor-svelte/health\",",
                "        healthcheckTimeout: 120,",
                "        env: {",
                "            DATABASE_URL: preserve(),",
                "            SESSION_SIGN_KEY: preserve(),",
                "        },",
                "    });",
                "",
                "    return project(\"shop\", {",
                "        resources: [app],",
                "    });",
                "});",
                "",
            ),
            railwayConfig("shop", "acme/shop", plan, listOf("DATABASE_URL", "SESSION_SIGN_KEY")).lines(),
        )
    }

    @Test
    fun `without a repository, commands or variables the file only has what is known`() {
        assertEquals(
            listOf(
                "import { defineRailway, project, service } from \"railway/iac\";",
                "",
                "export default defineRailway(() => {",
                "    const app = service(\"shop\", {",
                "        healthcheck: \"/_ktor-svelte/health\",",
                "        healthcheckTimeout: 120,",
                "    });",
                "",
                "    return project(\"shop\", {",
                "        resources: [app],",
                "    });",
                "});",
                "",
            ),
            railwayConfig("shop", null, null, emptyList()).lines(),
        )
    }
}
