package io.github.nijasc.ktor.svelte.gradle.tasks

import org.gradle.api.GradleException
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.Internal
import org.gradle.api.tasks.JavaExec
import org.gradle.api.tasks.TaskAction
import org.gradle.api.tasks.UntrackedTask
import org.gradle.process.CommandLineArgumentProvider
import java.io.File

internal const val VERIFY_REPORT_PROPERTY = "ktor.svelte.generateTsVerify"

internal fun staleTypeScriptProblem(
    report: File,
    projectDirectory: File,
): String? {
    if (!report.isFile) return null
    val base = projectDirectory.canonicalFile
    val stale =
        report
            .readLines()
            .filter { it.isNotBlank() }
            .map { path -> File(path).canonicalFile.relativeToOrSelf(base).invariantSeparatorsPath }
    if (stale.isEmpty()) return null
    return "Generated TypeScript is out of date: ${stale.joinToString()}. " +
        "Run svelteGenerateTs, or start the app in development mode, and commit the result."
}

@UntrackedTask(because = "Compares TypeScript generated by the app with the committed files")
public abstract class SvelteVerifyTsTask : JavaExec() {
    @get:Internal
    public abstract val reportFile: RegularFileProperty

    @get:Internal
    public abstract val projectDirectory: DirectoryProperty

    init {
        jvmArgumentProviders.add(VerifyReportArgument(reportFile))
    }

    @TaskAction
    override fun exec() {
        val report = reportFile.get().asFile
        report.delete()
        report.parentFile.mkdirs()
        super.exec()
        if (!report.isFile) {
            logger.lifecycle("ktor-svelte: generateTs is off, so there is no TypeScript to verify.")
            return
        }
        staleTypeScriptProblem(report, projectDirectory.get().asFile)?.let { throw GradleException(it) }
        logger.lifecycle("ktor-svelte: generated TypeScript is up to date.")
    }
}

private class VerifyReportArgument(
    @get:Internal
    val reportFile: RegularFileProperty,
) : CommandLineArgumentProvider {
    override fun asArguments(): Iterable<String> = listOf("-D$VERIFY_REPORT_PROPERTY=${reportFile.get().asFile.absolutePath}")
}
