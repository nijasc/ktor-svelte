package io.github.nijasc.ktor.svelte.gradle.libraries

import io.github.nijasc.ktor.svelte.gradle.DaisyCustomTheme
import io.github.nijasc.ktor.svelte.gradle.LocaleStrategy
import org.gradle.api.GradleException
import java.io.Serializable

internal const val GENERATED_DIR = "src/lib/ktor-svelte"
internal const val GENERATED_MARKER = "Generated by ktor-svelte. Do not edit."
internal const val THEME_COOKIE = "ktor_svelte_theme"
internal const val LOCALE_COOKIE = "ktor_svelte_locale"

internal val PACKAGE_VERSIONS =
    mapOf(
        "tailwindcss" to "^4.3.4",
        "@tailwindcss/vite" to "^4.3.4",
        "@tailwindcss/typography" to "^0.5.20",
        "@tailwindcss/forms" to "^0.5.11",
        "daisyui" to "^5.7.50",
        "@lucide/svelte" to "^1.67.0",
    )

public data class TailwindSpec(
    val typography: Boolean,
    val forms: Boolean,
) : Serializable

public data class DaisySpec(
    val themes: List<String>,
    val defaultTheme: String,
    val prefersDark: String?,
    val customThemes: List<DaisyCustomTheme>,
) : Serializable {
    val allThemes: List<String> get() = themes + customThemes.map { it.name }
}

public data class I18nSpec(
    val locales: List<String>,
    val defaultLocale: String,
    val strategy: LocaleStrategy,
) : Serializable

public data class LibrarySpec(
    val tailwind: TailwindSpec?,
    val daisy: DaisySpec?,
    val lucide: Boolean,
    val i18n: I18nSpec?,
    val devPort: Int,
    val generatedPackage: String,
) : Serializable {
    val isEmpty: Boolean get() = tailwind == null && daisy == null && !lucide && i18n == null
    val usesCss: Boolean get() = tailwind != null || daisy != null
    val usesHooks: Boolean get() = daisy != null || i18n != null

    val requiredPackages: Set<String>
        get() =
            buildSet {
                if (tailwind != null) {
                    add("tailwindcss")
                    add("@tailwindcss/vite")
                    if (tailwind.typography) add("@tailwindcss/typography")
                    if (tailwind.forms) add("@tailwindcss/forms")
                }
                if (daisy != null) add("daisyui")
                if (lucide) add("@lucide/svelte")
            }

    public fun validate() {
        if (daisy != null) {
            if (daisy.allThemes.isEmpty()) throw GradleException("daisyUi needs at least one theme.")
            if (daisy.defaultTheme !in daisy.allThemes) {
                throw GradleException("daisyUi defaultTheme '${daisy.defaultTheme}' is not one of ${daisy.allThemes}.")
            }
            if (daisy.prefersDark != null && daisy.prefersDark !in daisy.allThemes) {
                throw GradleException("daisyUi prefersDark '${daisy.prefersDark}' is not one of ${daisy.allThemes}.")
            }
            val invalid = daisy.customThemes.map { it.name }.filterNot { THEME_NAME.matches(it) }
            if (invalid.isNotEmpty()) {
                throw GradleException(
                    "Invalid daisyUi theme names: $invalid. Use lowercase letters, digits and dashes.",
                )
            }
        }
        if (i18n != null) {
            if (i18n.locales.isEmpty()) throw GradleException("i18n needs at least one locale.")
            if (i18n.defaultLocale !in i18n.locales) {
                throw GradleException("i18n defaultLocale '${i18n.defaultLocale}' is not one of ${i18n.locales}.")
            }
            val invalid = i18n.locales.filterNot { LOCALE_NAME.matches(it) }
            if (invalid.isNotEmpty()) throw GradleException("Invalid i18n locales: $invalid. Use tags such as en or pt-BR.")
        }
    }

    private companion object {
        val THEME_NAME = Regex("[a-z][a-z0-9-]*")
        val LOCALE_NAME = Regex("[a-z]{2,3}(-[A-Za-z0-9]{2,8})*")
    }
}
