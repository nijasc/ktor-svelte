package io.github.nijasc.ktor.svelte

import io.github.nijasc.ktor.svelte.internal.DeclaredEnvironment
import io.github.nijasc.ktor.svelte.internal.environmentExample
import kotlin.test.BeforeTest
import kotlin.test.Test
import kotlin.test.assertContains
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNull

enum class EnvMode { Open, Closed }

class AppEnvironment(
    scope: EnvironmentScope,
) {
    val databaseUrl = scope.string("DATABASE_URL", "JDBC URL of the database.", example = "jdbc:postgresql://localhost/app")
    val port = scope.int("PORT", "Port the server listens on", default = 8080)
    val signKey = scope.secret("SESSION_SIGN_KEY", "Signs the session cookie")
    val siteUrl = scope.optional("SITE_URL", "Public address, for links in emails", example = "https://example.com")
    val mode = scope.oneOf<EnvMode>("REGISTRATION", "Whether new people can sign up", default = EnvMode.Open)
    val debug = scope.boolean("DEBUG_SQL", "Logs every SQL statement", default = false)
    val apiToken = scope.optionalSecret("MAIL_TOKEN", "Token of the mail service")
    val workers = scope.int("WORKERS", "Number of background workers", example = 4)
}

class EnvironmentTest {
    @BeforeTest
    fun forget() {
        DeclaredEnvironment.clear()
        System.clearProperty("ktor.svelte.generateTsOnly")
    }

    private fun from(vararg values: Pair<String, String>): (String) -> String? = values.toMap()::get

    @Test
    fun `declared variables come back typed, with defaults for what is not set`() {
        val env =
            environment(
                from("DATABASE_URL" to "jdbc:h2:mem:x", "SESSION_SIGN_KEY" to "abc", "WORKERS" to "2", "REGISTRATION" to "closed"),
                ::AppEnvironment,
            )
        assertEquals("jdbc:h2:mem:x", env.databaseUrl)
        assertEquals(8080, env.port)
        assertEquals("abc", env.signKey)
        assertNull(env.siteUrl)
        assertEquals(EnvMode.Closed, env.mode)
        assertEquals(false, env.debug)
        assertNull(env.apiToken)
        assertEquals(2, env.workers)
    }

    @Test
    fun `everything that is missing or wrong is reported at once, in one table`() {
        val failure =
            assertFailsWith<EnvironmentException> {
                environment(
                    from("PORT" to "eighty", "REGISTRATION" to "maybe", "DEBUG_SQL" to "yes", "SESSION_SIGN_KEY" to ""),
                    ::AppEnvironment,
                )
            }
        assertEquals(listOf("DATABASE_URL", "PORT", "SESSION_SIGN_KEY", "REGISTRATION", "DEBUG_SQL", "WORKERS"), failure.variables)
        assertEquals(
            listOf(
                "The app cannot start: 6 environment variables are missing or wrong.",
                "",
                "  DATABASE_URL      missing                             JDBC URL of the database, such as jdbc:postgresql://localhost/app",
                "  PORT              \"eighty\" is not a whole number      Port the server listens on",
                "  SESSION_SIGN_KEY  missing                             Signs the session cookie",
                "  REGISTRATION      \"maybe\" is not one of Open, Closed  Whether new people can sign up",
                "  DEBUG_SQL         \"yes\" is not true or false          Logs every SQL statement",
                "  WORKERS           missing                             Number of background workers, such as 4",
                "",
                "Set them in the environment. .env.example lists every variable the app reads.",
            ),
            failure.message.orEmpty().lines(),
        )
    }

    @Test
    fun `one missing variable is told in the singular`() {
        val failure = assertFailsWith<EnvironmentException> { environment(from()) { secret("API_KEY", "Key of the payment service") } }
        assertContains(failure.message.orEmpty(), "The app cannot start: 1 environment variable is missing or wrong.")
        assertContains(failure.message.orEmpty(), "Set it in the environment.")
    }

    @Test
    fun `the example file lists every declared variable, with secrets left empty`() {
        environment(from("DATABASE_URL" to "x", "SESSION_SIGN_KEY" to "real-secret", "WORKERS" to "1"), ::AppEnvironment)
        assertEquals(
            listOf(
                "# Generated by ktor-svelte from the environment variables the app declares. Do not edit.",
                "",
                "# JDBC URL of the database. Required.",
                "DATABASE_URL=jdbc:postgresql://localhost/app",
                "",
                "# Port the server listens on. A whole number. Default: 8080.",
                "# PORT=8080",
                "",
                "# Signs the session cookie. Required. Secret.",
                "SESSION_SIGN_KEY=",
                "",
                "# Public address, for links in emails. Optional.",
                "# SITE_URL=https://example.com",
                "",
                "# Whether new people can sign up. One of Open, Closed. Default: Open.",
                "# REGISTRATION=Open",
                "",
                "# Logs every SQL statement. Either true or false. Default: false.",
                "# DEBUG_SQL=false",
                "",
                "# Token of the mail service. Optional. Secret.",
                "# MAIL_TOKEN=",
                "",
                "# Number of background workers. A whole number. Required.",
                "WORKERS=4",
                "",
            ),
            environmentExample(DeclaredEnvironment.variables()).orEmpty().lines(),
        )
        assertNull(environmentExample(emptyList()))
    }

    @Test
    fun `a run that only generates files does not need the environment`() {
        System.setProperty("ktor.svelte.generateTsOnly", "true")
        try {
            val env = environment(from(), ::AppEnvironment)
            assertEquals("jdbc:postgresql://localhost/app", env.databaseUrl)
            assertEquals("", env.signKey)
            assertEquals(4, env.workers)
            assertEquals(8, DeclaredEnvironment.variables().size)
        } finally {
            System.clearProperty("ktor.svelte.generateTsOnly")
        }
    }

    @Test
    fun `a name that is not an environment variable is refused`() {
        val failure = assertFailsWith<IllegalArgumentException> { environment(from()) { optional("database-url", "x") } }
        assertContains(failure.message.orEmpty(), "'database-url' is not a name for an environment variable.")
    }
}
