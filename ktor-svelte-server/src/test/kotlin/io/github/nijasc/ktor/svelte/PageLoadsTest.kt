package io.github.nijasc.ktor.svelte

import io.github.nijasc.ktor.svelte.internal.typescript.GeneratedOperation
import io.github.nijasc.ktor.svelte.internal.typescript.PageDataSpec
import io.github.nijasc.ktor.svelte.internal.typescript.PageLoadSpec
import io.github.nijasc.ktor.svelte.internal.typescript.pageLoadsSource
import io.ktor.server.application.install
import io.ktor.server.response.respond
import io.ktor.server.routing.get
import io.ktor.server.routing.post
import io.ktor.server.routing.routing
import io.ktor.server.testing.ApplicationTestBuilder
import io.ktor.server.testing.testApplication
import org.junit.jupiter.api.io.TempDir
import java.nio.file.Path
import kotlin.io.path.createDirectories
import kotlin.io.path.exists
import kotlin.io.path.readText
import kotlin.io.path.writeText
import kotlin.test.Test
import kotlin.test.assertContains
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class PageLoadsTest {
    @TempDir
    lateinit var dir: Path

    private val routes get() = dir.resolve("src/routes")
    private val taskPage get() = routes.resolve("(app)/tasks/[id]/+page.ts")

    private fun app(
        loads: SveltePageLoadsConfig.() -> Unit = {
            page("/tasks/[id]") {
                data("task", "tasks.get")
                data("comments", "tasks.getComments")
                data("members", "members.list")
            }
        },
        block: suspend ApplicationTestBuilder.() -> Unit,
    ) = testApplication {
        dir.resolve("package.json").writeText("{}")
        dir.resolve("src/lib").createDirectories()
        listOf("(app)/tasks/[id]", "(app)/board", "about").forEach { page ->
            routes.resolve(page).createDirectories()
            routes.resolve("$page/+page.svelte").writeText("<h1>Page</h1>\n")
        }
        val build = fixtureBuild()
        application {
            install(Svelte) {
                source = SvelteSource.Directory(build)
                dev { mode = DevMode.Never }
                generateTs = true
                generateTsOutput = dir.resolve("src/lib/api").toString()
                transport { json() }
                pageLoads(loads)
            }
            routing {
                get("/api/tasks/{id}") { call.respond(listOf("task")) }
                get("/api/tasks/{id}/comments") { call.respond(listOf("comment")) }
                post("/api/tasks") { call.respond(listOf("created")) }
                get("/api/members") { call.respond(listOf("member")) }
            }
        }
        block()
    }

    @Test
    fun `a page with pageLoads gets a typed load and a generated page file`() =
        app {
            startApplication()
            assertEquals(
                "import { apiWith } from './services.js';\n\n" +
                    "export async function loadTasksId(event: { fetch: typeof fetch; params: { id: string } }) {\n" +
                    "    const api = apiWith(event);\n" +
                    "    const [task, comments, members] = await Promise.all([\n" +
                    "        api.tasks.get(event.params.id, { silent: true }),\n" +
                    "        api.tasks.getComments(event.params.id, { silent: true }),\n" +
                    "        api.members.list({ silent: true })\n" +
                    "    ]);\n" +
                    "    return { task, comments, members };\n" +
                    "}\n",
                dir.resolve("src/lib/api/loads.ts").readText(),
            )
            assertContains(dir.resolve("src/lib/api/index.ts").readText(), "export * from './loads.js';")
            val page = taskPage.readText()
            assertTrue(page.startsWith("// Generated by ktor-svelte from pageLoads."))
            assertContains(page, "import { loadTasksId } from '#api';")
            assertContains(page, "export const load: PageLoad = (event) => loadTasksId(event);")
        }

    @Test
    fun `a generated page file goes away when its page leaves pageLoads, a hand-written one stays`() {
        routes.resolve("about").createDirectories()
        routes.resolve("about/+page.ts").writeText("export const prerender = true;\n")
        app { startApplication() }
        assertTrue(taskPage.exists())
        app(loads = { page("/board") { data("members", "members.list") } }) { startApplication() }
        assertFalse(taskPage.exists())
        assertTrue(routes.resolve("(app)/board/+page.ts").exists())
        assertEquals("export const prerender = true;\n", routes.resolve("about/+page.ts").readText())
        assertFalse(dir.resolve("src/lib/api/loads.ts").readText().contains("loadTasksId"))
    }

    @Test
    fun `a hand-written load is never overwritten and can call the generated one`() {
        routes.resolve("(app)/tasks/[id]").createDirectories()
        taskPage.writeText("export const load = () => ({});\n")
        app { startApplication() }
        assertEquals("export const load = () => ({});\n", taskPage.readText())
        assertContains(dir.resolve("src/lib/api/loads.ts").readText(), "export async function loadTasksId(", message = "it can still call the load")
    }

    @Test
    fun `operations that a page load cannot call are refused with what to do`() {
        val operations =
            listOf(
                GeneratedOperation("tasks.get", "GET", "/api/tasks/{id}", listOf("id"), listOf("string | number")),
                GeneratedOperation("tasks.post", "POST", "/api/tasks", needsInput = true),
                GeneratedOperation("tasks.search", "GET", "/api/tasks/search", optionalSlots = 1, needsInput = true),
                GeneratedOperation("numbers.get", "GET", "/api/numbers/{n}", listOf("n"), listOf("number")),
            )

        fun failure(
            page: String,
            operation: String,
            params: Map<String, String> = emptyMap(),
        ) = assertFailsWith<IllegalStateException> {
            pageLoadsSource(listOf(PageLoadSpec(page, listOf(PageDataSpec("value", operation, params)))), operations)
        }.message.orEmpty()

        assertContains(failure("/tasks/[id]", "tasks.nope"), "the API has no such route. Known: numbers.get, tasks.get")
        assertContains(failure("/tasks", "tasks.post"), "which is a POST. A page load only reads")
        assertContains(failure("/tasks", "tasks.search"), "needs a body, query or header that a page load cannot fill")
        assertContains(failure("/board", "tasks.get"), "needs the path parameter 'id', and the page '/board' has none")
        val mapped =
            pageLoadsSource(
                listOf(PageLoadSpec("/n/[value]", listOf(PageDataSpec("number", "numbers.get", mapOf("n" to "value"))))),
                operations,
            )
        assertContains(mapped, "api.numbers.get(Number(event.params.value), { silent: true })")
    }

    @Test
    fun `pageLoads is refused when it cannot work`() {
        fun refused(loads: SveltePageLoadsConfig.() -> Unit) =
            assertFailsWith<IllegalArgumentException> { app(loads) { startApplication() } }.message.orEmpty()

        assertContains(refused { page("tasks") { data("task", "tasks.get") } }, "pageLoads takes the path of a page")
        assertContains(refused { page("/board") {} }, "'/board' loads nothing")
        assertContains(refused { page("/board") { data("my-members", "members.list") } }, "must be a JavaScript name")
        assertContains(
            refused {
                page("/board") {
                    data("members", "members.list")
                    data("members", "members.list")
                }
            },
            "loads 'members' twice",
        )
        assertContains(refused { page("/board") { data("members", "list") } }, "such as \"tasks.get\"")
        assertContains(
            refused {
                page("/board") { data("members", "members.list") }
                page("/board/") { data("members", "members.list") }
            },
            "two pageLoads",
        )
    }
}
