package io.github.nijasc.ktor.svelte.internal

internal const val ENV_EXAMPLE_FILE = ".env.example"
private const val EXAMPLE_HEADER = "# Generated by ktor-svelte from the environment variables the app declares. Do not edit.\n"

internal class DeclaredVariable(
    val name: String,
    val description: String,
    val type: String,
    val required: Boolean,
    val default: String?,
    val example: String?,
    val secret: Boolean,
)

internal object DeclaredEnvironment {
    private val declared = linkedMapOf<String, DeclaredVariable>()

    fun add(variable: DeclaredVariable) {
        synchronized(declared) { declared[variable.name] = variable }
    }

    fun variables(): List<DeclaredVariable> = synchronized(declared) { declared.values.toList() }

    fun clear() {
        synchronized(declared) { declared.clear() }
    }
}

internal fun environmentTable(problems: Map<String, String>): String {
    val described = DeclaredEnvironment.variables().associateBy { it.name }
    val nameWidth = problems.keys.maxOf { it.length }
    val problemWidth = problems.values.maxOf { it.length }
    return problems.entries.joinToString("\n") { (name, problem) ->
        val variable = described[name]
        val hint =
            variable
                ?.example
                ?.takeIf { !variable.secret }
                ?.let { ", such as $it" }
                .orEmpty()
        "  ${name.padEnd(nameWidth)}  ${problem.padEnd(problemWidth)}  ${variable?.description.orEmpty().trimEnd('.')}$hint".trimEnd()
    }
}

private fun typeNote(type: String): String? =
    when {
        type == "text" -> null
        type == "true or false" -> "Either true or false."
        type.startsWith("one of ") -> type.replaceFirstChar { it.uppercase() } + "."
        else -> "A $type."
    }

internal fun environmentExample(variables: List<DeclaredVariable>): String? {
    if (variables.isEmpty()) return null
    return EXAMPLE_HEADER +
        variables.joinToString("") { variable ->
            val notes =
                listOfNotNull(
                    variable.description.trimEnd('.') + ".",
                    typeNote(variable.type),
                    if (variable.required) "Required." else variable.default?.let { "Default: $it." } ?: "Optional.",
                    "Secret.".takeIf { variable.secret },
                )
            val value = if (variable.secret) "" else variable.example ?: variable.default.orEmpty()
            "\n# ${notes.joinToString(" ")}\n${if (variable.required) "" else "# "}${variable.name}=$value\n"
        }
}
